"""Shared model of the repository layout, used by every tool in this directory.

The rules here mirror the Gradle convention plugin (gradle/build-logic/.../PluginExtension.kt)
so that metadata problems are caught without configuring Gradle, and so catalog tooling can
cross-check built APKs against the source tree they claim to come from.
"""
from __future__ import annotations

import hashlib
import re
import tomllib
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

PACKAGE_PREFIX = "eu.kanade.tachiyomi.animeextension"
APP_LABEL_PREFIX = "Aniyomi: "

LANG_RE = re.compile(r"^(?:[a-z]{2,3}|all|other)$")
NAME_RE = re.compile(r"^[a-z0-9]+$")
CLASS_RE = re.compile(r"^(?:\.[A-Za-z_][A-Za-z0-9_]*)+$")
SOURCE_LANG_RE = re.compile(r"^(?:[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*|all|other)$")

# Oldest lib level the host app still loads (Anikku ExtensionLoader.LIB_VERSION_MIN).
MIN_LIB_VERSION = 12

DENSITIES = ("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi")

_EXT_BLOCK_RE = re.compile(r"^ext\s*\{(?P<body>.*?)^\}", re.S | re.M)
_ASSIGN_RE = re.compile(r"^\s*(?P<key>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*(?P<value>.+?)\s*$")
_BASE_VERSION_RE = re.compile(r"baseVersionCode\s*=\s*(\d+)")


class MetadataError(ValueError):
    """A build.gradle `ext { }` block that cannot be interpreted."""


def repo_lib_version(root: Path = REPO_ROOT) -> int:
    """The extensions-lib level this repository targets (gradle/ase.versions.toml)."""
    with (root / "gradle" / "ase.versions.toml").open("rb") as fh:
        return int(tomllib.load(fh)["versions"]["extension-lib"])


def parse_literal(raw: str) -> str | int | bool:
    raw = raw.strip()
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "'\"":
        value = raw[1:-1]
        if raw[0] == '"' and "$" in value:
            raise MetadataError(f"GString interpolation is not allowed: {raw}")
        return value
    if raw in ("true", "false"):
        return raw == "true"
    if re.fullmatch(r"-?\d+", raw):
        return int(raw)
    raise MetadataError(f"Unsupported value (use a string, integer or boolean literal): {raw}")


def _strip_comment(line: str) -> str:
    """Removes a trailing `//` comment that is not inside a quoted string."""
    quote = None
    for i, ch in enumerate(line):
        if quote:
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        elif line.startswith("//", i):
            return line[:i]
    return line


def parse_ext_block(text: str) -> dict[str, str | int | bool]:
    """Parses the literal assignments of a Groovy `ext { }` block."""
    match = _EXT_BLOCK_RE.search(text)
    if not match:
        raise MetadataError("missing top-level 'ext { }' block")
    values: dict[str, str | int | bool] = {}
    for line in match["body"].splitlines():
        line = _strip_comment(line).strip()
        if not line:
            continue
        assignment = _ASSIGN_RE.match(line)
        if not assignment:
            raise MetadataError(f"cannot parse line in ext block: {line!r}")
        key = assignment["key"]
        if key in values:
            raise MetadataError(f"duplicate key '{key}'")
        values[key] = parse_literal(assignment["value"])
    return values


def source_id(name: str, lang: str, version_id: int = 1) -> int:
    """Source id as generated by AnimeHttpSource.generateId: the first 64 bits of
    MD5("<name lowercase>/<lang>/<versionId>") with the sign bit cleared."""
    digest = hashlib.md5(f"{name.lower()}/{lang}/{version_id}".encode()).digest()
    return int.from_bytes(digest[:8], "big") & 0x7FFF_FFFF_FFFF_FFFF


@dataclass
class Extension:
    lang: str
    name: str
    path: Path
    metadata: dict[str, str | int | bool] = field(default_factory=dict)
    errors: list[str] = field(default_factory=list)
    version_code: int | None = None

    @property
    def module(self) -> str:
        return f":src:{self.lang}:{self.name}"

    @property
    def pkg(self) -> str:
        return f"{PACKAGE_PREFIX}.{self.lang}.{self.name}"

    @property
    def lib_version(self) -> int | None:
        value = self.metadata.get("libVersion")
        return value if isinstance(value, int) else None

    @property
    def version_name(self) -> str | None:
        if self.version_code is None or self.lib_version is None:
            return None
        return f"{self.lib_version}.{self.version_code}"

    @property
    def apk_name(self) -> str | None:
        """File name the catalog uses: `aniyomi-<lang>.<name>-v<versionName>.apk`."""
        return f"aniyomi-{self.lang}.{self.name}-v{self.version_name}.apk" if self.version_name else None

    @property
    def source_dir(self) -> Path:
        return self.path / "src" / Path(*PACKAGE_PREFIX.split(".")) / self.lang / self.name


def theme_base_version(root: Path, theme: str) -> int | None:
    build = root / "lib-multisrc" / theme / "build.gradle.kts"
    if not build.is_file():
        return None
    match = _BASE_VERSION_RE.search(build.read_text("utf-8"))
    return int(match[1]) if match else None


def load_extension(root: Path, lang: str, name: str) -> Extension:
    """Reads and validates one module's metadata; problems are collected in `errors`."""
    path = root / "src" / lang / name
    ext = Extension(lang, name, path)
    if not LANG_RE.match(lang):
        ext.errors.append(f"invalid language directory '{lang}' (2-3 lowercase letters, 'all' or 'other')")
    if not NAME_RE.match(name):
        ext.errors.append(f"invalid module name '{name}' (lowercase ASCII letters and digits only)")
    build = path / "build.gradle"
    if not build.is_file():
        ext.errors.append("missing build.gradle")
        return ext
    text = build.read_text("utf-8")
    try:
        meta = parse_ext_block(text)
    except MetadataError as e:
        ext.errors.append(f"build.gradle: {e}")
        return ext
    ext.metadata = meta

    if "apply plugin: 'ase.extension'" not in text and 'apply plugin: "ase.extension"' not in text:
        ext.errors.append("build.gradle must apply the 'ase.extension' plugin")
    if "pkgNameSuffix" in meta:
        ext.errors.append("'pkgNameSuffix' is not supported")

    ext_name = meta.get("extName")
    if not isinstance(ext_name, str) or not ext_name.strip():
        ext.errors.append("'extName' must be a non-empty string")
    elif any(ord(c) < 0x20 or ord(c) >= 0x180 for c in ext_name):
        ext.errors.append("'extName' must be romanized")

    ext_class = meta.get("extClass")
    if not isinstance(ext_class, str) or not CLASS_RE.match(ext_class):
        ext.errors.append("'extClass' must look like '.MySource'")

    if not isinstance(meta.get("isNsfw"), bool):
        ext.errors.append("'isNsfw' must be set explicitly to true or false")

    max_lib = repo_lib_version(root)
    lib = meta.setdefault("libVersion", max_lib)
    if not isinstance(lib, int) or not MIN_LIB_VERSION <= lib <= max_lib:
        ext.errors.append(f"'libVersion' must be an integer within {MIN_LIB_VERSION}..{max_lib}")

    theme = meta.get("themePkg")
    if theme is None:
        code = meta.get("extVersionCode")
        if isinstance(code, bool) or not isinstance(code, int) or code < 1:
            ext.errors.append("'extVersionCode' must be a positive integer")
        else:
            ext.version_code = code
    else:
        override = meta.get("overrideVersionCode")
        base = theme_base_version(root, str(theme))
        if "extVersionCode" in meta:
            ext.errors.append("use 'overrideVersionCode' instead of 'extVersionCode' with 'themePkg'")
        if base is None:
            ext.errors.append(f"theme 'lib-multisrc/{theme}' is missing or has no baseVersionCode")
        if isinstance(override, bool) or not isinstance(override, int) or override < 0:
            ext.errors.append("'overrideVersionCode' must be a non-negative integer")
        elif base is not None:
            ext.version_code = base + override
    return ext


def discover_extensions(root: Path = REPO_ROOT) -> list[Extension]:
    src = root / "src"
    if not src.is_dir():
        return []
    found = []
    for lang_dir in sorted(p for p in src.iterdir() if p.is_dir() and not p.name.startswith(".")):
        for module_dir in sorted(p for p in lang_dir.iterdir() if p.is_dir() and not p.name.startswith(".") and p.name != "build"):
            found.append(load_extension(root, lang_dir.name, module_dir.name))
    return found
